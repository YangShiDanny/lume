import { useCallback, useEffect, useRef, useState, type PointerEvent as ReactPointerEvent } from 'react';
import { BlocklyWorkspace, type WorkspaceApi } from './components/BlocklyWorkspace';
import { BootScreen } from './components/BootScreen';
import { CodePanel } from './components/CodePanel';
import {
  BlocksIcon,
  BookIcon,
  CodeIcon,
  MoonIcon,
  PlayIcon,
  ResetIcon,
  StarIcon,
  SunIcon,
  ZoomInIcon,
  ZoomOutIcon,
} from './components/Icons';
import { SyntaxSheet } from './components/SyntaxSheet';
import { Tour } from './components/Tour';
import { Wallpaper } from './components/Wallpaper';

type WindowState = 'normal' | 'min' | 'max' | 'closed';

const clockText = () =>
  new Intl.DateTimeFormat('zh-CN', { hour: '2-digit', minute: '2-digit', hour12: false }).format(new Date());

export default function App() {
  const initialTheme =
    typeof document !== 'undefined' && document.documentElement.dataset.theme === 'light' ? 'light' : 'dark';
  const [theme, setTheme] = useState<'dark' | 'light'>(initialTheme);
  const [code, setCode] = useState('# Generated by Lume Studio · 积木 → Lume 源码\n');
  const [blockCount, setBlockCount] = useState(0);
  const [codeWidth, setCodeWidth] = useState(440);
  const [codeVisible, setCodeVisible] = useState(true);
  const [winState, setWinState] = useState<WindowState>('normal');
  const [syntaxOpen, setSyntaxOpen] = useState(false);
  const [tourOpen, setTourOpen] = useState(false);
  const [toast, setToast] = useState('');
  const [clock, setClock] = useState(clockText);
  const [booting, setBooting] = useState(() => {
    try {
      return sessionStorage.getItem('lume.blockly.booted') !== '1';
    } catch {
      return true;
    }
  });
  const workspaceRef = useRef<WorkspaceApi>(null);

  useEffect(() => {
    const timer = window.setInterval(() => setClock(clockText()), 30_000);
    return () => window.clearInterval(timer);
  }, []);

  useEffect(() => {
    if (!toast) return;
    const timer = window.setTimeout(() => setToast(''), 1800);
    return () => window.clearTimeout(timer);
  }, [toast]);

  const finishBoot = useCallback(() => {
    setBooting(false);
    try {
      sessionStorage.setItem('lume.blockly.booted', '1');
    } catch {
      // 隐私模式下忽略
    }
  }, []);

  useEffect(() => {
    if (booting) return;
    let seen = false;
    try {
      seen = sessionStorage.getItem('lume.blockly.tour') === '1';
    } catch {
      // 忽略存储失败
    }
    if (seen) return;
    const timer = window.setTimeout(() => setTourOpen(true), 450);
    return () => window.clearTimeout(timer);
  }, [booting]);

  const finishTour = useCallback(() => {
    setTourOpen(false);
    try {
      sessionStorage.setItem('lume.blockly.tour', '1');
    } catch {
      // 隐私模式下忽略
    }
  }, []);

  const toggleTheme = () => {
    const next = theme === 'dark' ? 'light' : 'dark';
    setTheme(next);
    document.documentElement.dataset.theme = next;
    document.documentElement.style.colorScheme = next;
    document.querySelector('meta[name="theme-color"]')?.setAttribute('content', next === 'light' ? '#f2f2f1' : '#050507');
    try {
      localStorage.setItem('lume.blockly.theme', next);
    } catch {
      // 忽略存储失败
    }
    setToast(next === 'dark' ? 'DARK THEME' : 'LIGHT THEME');
  };

  const startSplit = (event: ReactPointerEvent<HTMLDivElement>) => {
    event.currentTarget.setPointerCapture(event.pointerId);
    const move = (e: PointerEvent) => {
      const next = window.innerWidth - e.clientX - 24;
      setCodeWidth(Math.max(320, Math.min(620, next)));
    };
    const up = () => {
      window.removeEventListener('pointermove', move);
      window.removeEventListener('pointerup', up);
    };
    window.addEventListener('pointermove', move);
    window.addEventListener('pointerup', up);
  };

  const openWindow = () => setWinState('normal');

  return (
    <div className="studio-root">
      <Wallpaper theme={theme} />
      <div className="wall-glow" aria-hidden="true" />
      <div className="wall-mark" aria-hidden="true">
        <span>LUME</span>
        <i />
        <span>BLOCK STUDIO</span>
      </div>

      {booting && <BootScreen onDone={finishBoot} />}

      <div className={`desktop ${booting ? 'booting' : 'awake'}`}>
        <header className="menubar">
          <div className="menubar-side">
            <button className="mb-logo" aria-label="Lume Studio" onClick={openWindow}>
              <StarIcon width={16} height={16} />
            </button>
            <span className="mb-app">Lume Studio</span>
            <span className="mb-ver">v0.1 · FRONTEND</span>
            <span className="mb-divider" />
            <span className="mb-crumb">workspace.lume</span>
          </div>
          <div className="menubar-side menubar-right">
            <span className="mb-build">BLOCKS → LUME SOURCE</span>
            <button className="mb-btn" onClick={() => setSyntaxOpen(true)} aria-label="打开语法速览">
              <BookIcon width={14} height={14} />
              <span>语法</span>
            </button>
            <button className="mb-btn" onClick={() => setTourOpen(true)} aria-label="重播首次使用引导">
              <StarIcon width={14} height={14} />
              <span>导览</span>
            </button>
            <button className="mb-btn mb-icon" onClick={toggleTheme} aria-label="切换明暗主题" title="切换主题">
              {theme === 'dark' ? <SunIcon width={15} height={15} /> : <MoonIcon width={15} height={15} />}
            </button>
            <time className="mb-clock">{clock}</time>
          </div>
        </header>

        <div className="desk-icons">
          <button className="desk-icon" onClick={openWindow}>
            <span className="desk-icon-art">
              <BlocksIcon width={26} height={26} />
            </span>
            <span>workspace.lume</span>
          </button>
          <button className="desk-icon" onClick={() => setSyntaxOpen(true)}>
            <span className="desk-icon-art">
              <BookIcon width={26} height={26} />
            </span>
            <span>语法速览</span>
          </button>
        </div>

        <main className={`windows ${winState === 'max' ? 'is-max' : ''}`} hidden={winState === 'closed' || winState === 'min'}>
          <section className="window focused" aria-label="积木工作台">
            <header className="win-titlebar">
              <div className="win-lights">
                <button
                  className="win-light close"
                  aria-label="关闭窗口"
                  onClick={() => setWinState('closed')}
                />
                <button className="win-light min" aria-label="最小化窗口" onClick={() => setWinState('min')} />
                <button
                  className="win-light max"
                  aria-label="切换最大化"
                  onClick={() => setWinState(winState === 'max' ? 'normal' : 'max')}
                />
              </div>
              <span className="win-title">WORKSPACE.LUME</span>
              <span className="win-meta">BLOCKLY WORKSPACE · AUTO COMPILE</span>
              <div className="win-tools">
                <button className="icon-btn" onClick={() => workspaceRef.current?.zoomOut()} aria-label="缩小积木" title="缩小">
                  <ZoomOutIcon />
                </button>
                <button className="icon-btn" onClick={() => workspaceRef.current?.zoomIn()} aria-label="放大积木" title="放大">
                  <ZoomInIcon />
                </button>
                <button className="icon-btn" onClick={() => workspaceRef.current?.fit()} aria-label="回到积木中心" title="居中">
                  <StarIcon width={16} height={16} />
                </button>
                <span className="win-tool-sep" />
                <button
                  className={`icon-btn ${codeVisible ? 'active' : ''}`}
                  onClick={() => setCodeVisible((v) => !v)}
                  aria-label="切换源码面板"
                  title="切换源码面板"
                >
                  <CodeIcon />
                </button>
              </div>
            </header>

            <div className="win-body">
              <BlocklyWorkspace
                ref={workspaceRef}
                theme={theme}
                onChange={(nextCode, count) => {
                  setCode(nextCode);
                  setBlockCount(count);
                }}
              />
              {codeVisible && (
                <>
                  <div className="splitter" onPointerDown={startSplit} role="separator" aria-label="调整源码面板宽度" />
                  <div className="code-slot" style={{ width: codeWidth }}>
                    <CodePanel code={code} blockCount={blockCount} />
                  </div>
                </>
              )}
            </div>

            <footer className="win-status">
              <span className="status-dot" />
              <span>SOURCE SYNCED</span>
              <span className="status-sep">/</span>
              <span>{theme === 'dark' ? 'DARK' : 'LIGHT'}</span>
              <span className="status-sep">/</span>
              <span>NO RUNTIME ATTACHED</span>
              <span className="status-right">UTF-8 · LUME v0.1</span>
            </footer>
          </section>
        </main>

        <nav className="dock" aria-label="Dock">
          <div className="dock-inner">
            <button className={`dock-item ${winState !== 'closed' ? 'running' : ''}`} onClick={openWindow}>
              <span className="dock-tile">
                <BlocksIcon />
              </span>
              <span className="dock-tip">积木工作台</span>
            </button>
            <button className="dock-item" onClick={() => setCodeVisible((v) => !v)}>
              <span className="dock-tile">
                <CodeIcon />
              </span>
              <span className="dock-tip">源码面板</span>
            </button>
            <button className="dock-item" onClick={() => setSyntaxOpen(true)}>
              <span className="dock-tile">
                <BookIcon />
              </span>
              <span className="dock-tip">语法速览</span>
            </button>
            <button className="dock-item" onClick={() => workspaceRef.current?.reset()}>
              <span className="dock-tile">
                <ResetIcon />
              </span>
              <span className="dock-tip">重置示例</span>
            </button>
            <button className="dock-item" onClick={toggleTheme}>
              <span className="dock-tile">
                {theme === 'dark' ? <SunIcon /> : <MoonIcon />}
              </span>
              <span className="dock-tip">切换主题</span>
            </button>
            <span className="dock-sep" />
            <button className="dock-item dock-disabled" aria-disabled="true" title="运行器尚未接入">
              <span className="dock-tile">
                <PlayIcon />
              </span>
              <span className="dock-tip">运行（暂未接入）</span>
            </button>
          </div>
        </nav>

        {syntaxOpen && <SyntaxSheet onClose={() => setSyntaxOpen(false)} />}
        {tourOpen && <Tour onDone={finishTour} />}
        {toast && <div className="toast">{toast}</div>}
      </div>
    </div>
  );
}
